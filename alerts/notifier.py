import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from loguru import logger
from dotenv import load_dotenv
from datetime import datetime

load_dotenv()

SENDER    = os.getenv("GMAIL_SENDER", "")
PASSWORD  = os.getenv("GMAIL_APP_PASSWORD", "")
RECIPIENT = os.getenv("GMAIL_RECIPIENT", "")


def send_alert(subject: str, body: str) -> bool:
    if not all([SENDER, PASSWORD, RECIPIENT]):
        logger.warning("[ALERT] Gmail credentials not set in .env")
        return False
    if SENDER == "your_gmail@gmail.com":
        logger.warning("[ALERT] Placeholder credentials detected.")
        return False
    try:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"]    = SENDER
        msg["To"]      = RECIPIENT
        html = f"""
        <html>
        <body style="font-family:Arial;background:#0e1117;color:white;padding:20px">
        <h2 style="color:#00FF88">VideoGPT Alert</h2>
        <pre style="background:#1a1a1a;padding:15px;border-radius:8px;
                    color:#FFD700;font-size:13px">{body}</pre>
        <p style="color:#888;font-size:11px">
          Generated by VideoGPT | {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
        </p>
        </body>
        </html>
        """
        msg.attach(MIMEText(html, "html"))
        with smtplib.SMTP_SSL("smtp.gmail.com", 465) as server:
            server.login(SENDER, PASSWORD)
            server.sendmail(SENDER, RECIPIENT, msg.as_string())
        logger.info(f"[ALERT] Email sent to {RECIPIENT}")
        return True
    except Exception as e:
        logger.error(f"[ALERT] Email failed: {e}")
        return False


def build_alert_body(result: dict) -> str:
    plate    = result.get("plate", "N/A")
    found    = result.get("cameras_found", [])
    searched = result.get("cameras_searched", [])
    match    = result.get("match_pct", 0)
    timeline = result.get("timeline", [])
    gaps     = result.get("gaps", [])

    lines = [
        "VEHICLE INVESTIGATION REPORT",
        "=" * 42,
        f"Plate Number    : {plate}",
        f"Cameras Searched: {', '.join(searched) if searched else 'All'}",
        f"Cameras Found   : {', '.join(found) if found else 'None'}",
        f"Match Score     : {match}%",
        "",
        "TIMELINE:"
    ]
    for t in timeline:
        lines.append(
            f"  [{t['camera_id'].upper()}] {t['timestamp_real']} | "
            f"{t['vehicle_type']} | {t['color']} | {t['direction']}"
        )
    if gaps:
        lines.append("\nTRAVEL GAPS:")
        for g in gaps:
            lines.append(
                f"  {g['from'].upper()} -> {g['to'].upper()} : {g['gap_str']}"
            )
    lines.append(f"\n{result.get('summary', '')}")
    return "\n".join(lines)
